$livekitNlb = @"
# GKE external passthrough NLB for LiveKit WebRTC media (UDP $livekitStart-$livekitEnd) + RTC TCP.
# Generated by k8s/scripts/generate-media-ports.ps1
# After apply: kubectl get svc livekit-media -n kzys -o jsonpath='{.status.loadBalancer.ingress[0].ip}'
apiVersion: v1
kind: Service
metadata:
  name: livekit-media
  namespace: kzys
  labels:
    app: livekit
    app.kubernetes.io/part-of: project-k
  annotations:
    cloud.google.com/l4-rbs: "enabled"
    networking.gke.io/load-balancer-type: "External"
spec:
  type: LoadBalancer
  externalTrafficPolicy: Local
  selector:
    app: livekit
  ports:
    - name: rtc-tcp
      port: 7881
      targetPort: 7881
      protocol: TCP
$lkServiceUdp
"@

