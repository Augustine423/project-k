# Regenerates K8s NLB + deployment UDP containerPort lists for load-test ranges:
#   LiveKit WebRTC: 50000-59000
#   Coturn relay:   20000-29000
#
# Usage (from repo root):
#   pwsh k8s/scripts/generate-media-ports.ps1

$ErrorActionPreference = "Stop"
$root = Split-Path -Parent (Split-Path -Parent $PSScriptRoot)

$livekitStart = 50000
$livekitEnd   = 59000
$turnStart    = 20000
$turnEnd      = 29000

function Format-ContainerUdpPorts([int]$Start, [int]$End) {
    ($Start..$End | ForEach-Object {
        "            - containerPort: $_"
        "              protocol: UDP"
    }) -join "`n"
}

function Format-ServiceUdpPorts([string]$Prefix, [int]$Start, [int]$End) {
    ($Start..$End | ForEach-Object {
        "    - name: ${Prefix}-$_"
        "      port: $_"
        "      targetPort: $_"
        "      protocol: UDP"
    }) -join "`n"
}

$lkContainerUdp = Format-ContainerUdpPorts $livekitStart $livekitEnd
$turnContainerUdp = Format-ContainerUdpPorts $turnStart $turnEnd
$lkServiceUdp = Format-ServiceUdpPorts "rtc-udp" $livekitStart $livekitEnd
$turnServiceUdp = Format-ServiceUdpPorts "turn-relay" $turnStart $turnEnd

$livekitDeployment = @"
